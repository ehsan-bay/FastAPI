const { chromium, devices } = require('playwright');
const B = 'http://localhost:8000', OUT = process.argv[2], TOK = process.argv[3];
const css = `::-webkit-scrollbar{display:none} *{scrollbar-width:none}`;
(async () => {
  const b = await chromium.launch();
  const login = async (ctx, email, pw) => {
    const r = await (await ctx.request.post(B + '/api/auth/login', { data: { email, password: pw } })).json();
    const p = await ctx.newPage();
    await p.addInitScript((t) => localStorage.setItem('salamat.token', t), r.token);
    return p;
  };
  const go = async (p, path) => { await p.goto(B + path); await p.addStyleTag({ content: css }); await p.waitForLoadState('networkidle'); await p.waitForTimeout(700); };
  const m = await b.newContext({ ...devices['Pixel 7'], deviceScaleFactor: 2, locale: 'fa-IR' });
  const p = await login(m, 'demo@salamatyar.ir', 'demo1234');
  await go(p, '/pay/' + TOK);
  await p.screenshot({ path: OUT + '/pay.png' });
  await p.getByRole('button', { name: /^پرداخت/ }).click();
  await p.getByText('پرداخت موفق').waitFor();
  await p.addStyleTag({ content: css }); await p.waitForTimeout(400);
  await p.screenshot({ path: OUT + '/receipt.png' });
  await go(p, '/wallet');
  await p.screenshot({ path: OUT + '/wallet.png' });
  const d = await b.newContext({ viewport: { width: 1360, height: 860 }, deviceScaleFactor: 2, locale: 'fa-IR' });
  const a = await login(d, 'admin@salamatyar.ir', 'Admin12345');
  await go(a, '/admin');
  await a.getByText('پرداخت‌های امروز').waitFor(); await a.waitForTimeout(500);
  await a.screenshot({ path: OUT + '/admin-report.png' });
  await a.getByRole('tab', { name: /پزشکان/ }).click(); await a.waitForTimeout(800);
  await a.screenshot({ path: OUT + '/admin-doctors.png' });
  await a.getByRole('button', { name: 'QR' }).first().click(); await a.locator('.modal img').waitFor(); await a.waitForTimeout(400);
  await a.screenshot({ path: OUT + '/admin-qr.png' });
  await a.getByRole('button', { name: 'بستن' }).click();
  await a.getByRole('tab', { name: /پرداخت‌ها/ }).click(); await a.waitForTimeout(900);
  await a.screenshot({ path: OUT + '/admin-payments.png' });
  await a.getByRole('tab', { name: /کاربران/ }).click(); await a.waitForTimeout(800);
  await a.screenshot({ path: OUT + '/admin-users.png' });
  await b.close();
  console.log('ok');
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
